using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp.Syntax;

namespace EtAndHkIde.SourceGenerators
{
    [Generator] // needed
    public sealed class SiteIndexGenerator : IIncrementalGenerator
    {
        public void Initialize(IncrementalGeneratorInitializationContext context)
        {
            var pageModels = context.SyntaxProvider
                .CreateSyntaxProvider(
                predicate: static (node, _) => node is ClassDeclarationSyntax,
                transform: static (ctx, _) => GetPageModelInfo(ctx))
                .Where(static m => m is not null)
                .Collect();
            context.RegisterSourceOutput(pageModels, static (spc, pages) =>
            {
                var source = GenerateSiteIndex(pages);
                spc.AddSource("SiteIndex.g.cs", source);
            });           
        }

        private static PageModelInfo? GetPageModelInfo(GeneratorSyntaxContext context)
        {
            var classSyntax = (ClassDeclarationSyntax)context.Node;
            var classSymbol = context.SemanticModel.GetDeclaredSymbol(classSyntax) as INamedTypeSymbol;
            if (classSymbol == null)
            {
                return null;
            }
            if (!InheritsFrom(classSymbol, "SitePageModel"))
            {
                return null;
            }

            var ns = classSymbol.ContainingNamespace.ToDisplayString();
            var name = classSymbol.Name;

            var filePath = classSyntax.SyntaxTree.FilePath;
            var route = DeriveRoute(filePath);

            return new PageModelInfo(ns, name, route);

        }

        private static string GenerateSiteIndex(IEnumerable<PageModelInfo> pages)
        {
            var entries = string.Join(",\n        ",
                pages.Select(p => $"\"{p.Namespace}.{p.Name}\""));
            return $$"""
                // <auto-generated />
                namespace EtAndHkIde.Web;

                public static class SiteIndex
                {
                    public static readonly string[] Pages = new[]
                    {
                        {{entries}}
                    };
                }
                """;
        }

        private static bool InheritsFrom(INamedTypeSymbol symbol, string baseName)
        {
            while (symbol.BaseType != null)
            {
                if (symbol.BaseType.Name == baseName)
                    return true;

                symbol = symbol.BaseType;
            }
            return false;
        }

        private static string DeriveRoute(string? filePath)
        {
            // Example: /Pages/People/EtIdeInIndiana.cshtml.cs → /People/EtIdeInIndiana
            if (filePath == null)
                return "";

            var idx = filePath.IndexOf("Pages");
            var sub = filePath.Substring(idx + "Pages".Length);
            sub = sub.Replace(".cshtml.cs", "").Replace("\\", "/");
            return sub;
        }

        private record PageModelInfo(string Namespace, string Name, string Route);

    }
}
